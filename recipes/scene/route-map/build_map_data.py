"""Build the compact map data modules for scene.route-map from Natural Earth GeoJSON.

Natural Earth (naturalearthdata.com) is in the public domain. Run with the
downloaded files (github.com/nvkelso/natural-earth-vector/tree/master/geojson):

  python -I build_map_data.py land ne_50m_land.geojson land-50m.js 0.015 0.0005
  python -I build_map_data.py borders ne_50m_admin_0_boundary_lines_land.geojson borders-50m.js 0.02

land: polygon rings, Douglas-Peucker simplified at TOLERANCE degrees, rings under
MIN_AREA square degrees dropped. borders: international boundary lines only
(features whose FEATURECLA is "International boundary (verify)"; disputed and
other classes are left out). Coordinates are quantised to 1/100 degree and
delta encoded, as [dlon, dlat, dlon, dlat, ...] per ring or line.
"""
import json
import math
import sys

mode, src, out, tol = sys.argv[1], sys.argv[2], sys.argv[3], float(sys.argv[4])
min_area = float(sys.argv[5]) if len(sys.argv) > 5 else 0.0
data = json.load(open(src, encoding="utf-8"))


def dp(points, eps):
    if len(points) < 3:
        return points
    keep = [False] * len(points)
    keep[0] = keep[-1] = True
    stack = [(0, len(points) - 1)]
    while stack:
        a, b = stack.pop()
        ax, ay = points[a]
        bx, by = points[b]
        dx, dy = bx - ax, by - ay
        length = math.hypot(dx, dy)
        best, idx = -1.0, -1
        for i in range(a + 1, b):
            px, py = points[i]
            d = abs(dy * px - dx * py + bx * ay - by * ax) / length if length > 0 else math.hypot(px - ax, py - ay)
            if d > best:
                best, idx = d, i
        if best > eps and idx > 0:
            keep[idx] = True
            stack += [(a, idx), (idx, b)]
    return [p for p, k in zip(points, keep) if k]


def area(ring):
    return abs(sum(ring[i][0] * ring[i - 1][1] - ring[i - 1][0] * ring[i][1] for i in range(len(ring)))) / 2


def encode(points, minimum):
    q = []
    for x, y in points:
        p = (round(x * 100), round(max(-85, min(85, y)) * 100))
        if not q or p != q[-1]:
            q.append(p)
    if len(q) < minimum:
        return None
    flat, px, py = [], 0, 0
    for x, y in q:
        flat += [x - px, y - py]
        px, py = x, y
    return flat


shapes, n_in, n_out = [], 0, 0
for feature in data["features"]:
    geometry = feature["geometry"]
    if mode == "land":
        polygons = geometry["coordinates"] if geometry["type"] == "MultiPolygon" else [geometry["coordinates"]]
        for polygon in polygons:
            for ring in polygon:
                n_in += len(ring)
                if area(ring) < min_area:
                    continue
                r = ring[:-1] if ring[0] == ring[-1] else ring
                half = len(r) // 2  # simplify two halves so the closed ring keeps its shape
                simplified = dp(r[: half + 1], tol)[:-1] + dp(r[half:] + [r[0]], tol)[:-1]
                flat = encode(simplified, 4)
                if flat:
                    shapes.append(flat)
                    n_out += len(flat) // 2
    else:
        if feature["properties"].get("FEATURECLA") != "International boundary (verify)":
            continue
        lines = geometry["coordinates"] if geometry["type"] == "MultiLineString" else [geometry["coordinates"]]
        for line in lines:
            n_in += len(line)
            flat = encode(dp(line, tol), 2)
            if flat:
                shapes.append(flat)
                n_out += len(flat) // 2

doc = {"format": "delta-encoded " + ("rings" if mode == "land" else "lines") + ", 1/100 degree (lon, lat), WGS84",
       "source": f"Natural Earth 1:50m, VERSION 5.2.0-pre ({data.get('name')}), public domain, naturalearthdata.com",
       "simplified": f"Douglas-Peucker {tol} deg" + (f", rings under {min_area} sq deg dropped" if mode == "land" else
                                                      ", international boundaries only (no disputed lines)"),
       "shapes": shapes}
with open(out, "w", encoding="utf-8") as handle:
    handle.write("// Generated by build_map_data.py from Natural Earth (public domain). Do not edit.\n"
                 "export default " + json.dumps(doc, separators=(",", ":"), ensure_ascii=True) + ";\n")
print(f"{mode}: points {n_in} -> {n_out}, shapes {len(shapes)}")
